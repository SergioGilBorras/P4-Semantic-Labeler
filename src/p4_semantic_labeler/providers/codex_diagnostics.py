"""Allow-listed, non-sensitive Codex Bridge diagnostic categories and codes."""

AUTHENTICATION = "AUTHENTICATION"
CLI_UNAVAILABLE = "CLI_UNAVAILABLE"
CAPABILITY_UNAVAILABLE = "CAPABILITY_UNAVAILABLE"
PERMISSION_DENIED = "PERMISSION_DENIED"
TIMEOUT = "TIMEOUT"
BRIDGE_EXECUTION_FAILED = "BRIDGE_EXECUTION_FAILED"
EMPTY_RESPONSE = "EMPTY_RESPONSE"
UNKNOWN = "UNKNOWN"

DIAGNOSTIC_CATEGORIES = frozenset(
    {
        AUTHENTICATION,
        CLI_UNAVAILABLE,
        CAPABILITY_UNAVAILABLE,
        PERMISSION_DENIED,
        TIMEOUT,
        BRIDGE_EXECUTION_FAILED,
        EMPTY_RESPONSE,
        UNKNOWN,
    }
)

STRUCTURED_ERROR_CATEGORIES = {
    # Legacy spellings recognized by the previous adapter implementation.
    "AUTHENTICATION_ERROR": AUTHENTICATION,
    "BRIDGE_TIMEOUT": TIMEOUT,
    "CODEX_AUTH_REQUIRED": AUTHENTICATION,
    "CODEX_NOT_FOUND": CLI_UNAVAILABLE,
    "CODEX_TIMEOUT": TIMEOUT,
    "BRIDGE_WAIT_TIMEOUT": TIMEOUT,
    "CODEX_EMPTY_RESPONSE": EMPTY_RESPONSE,
    "OUTPUT_LAST_MESSAGE_MISSING": BRIDGE_EXECUTION_FAILED,
    "STRUCTURED_OUTPUT_INVALID": BRIDGE_EXECUTION_FAILED,
    "CODEX_EXIT_NONZERO": BRIDGE_EXECUTION_FAILED,
    "CODEX_OUTPUT_LIMIT": BRIDGE_EXECUTION_FAILED,
    "CODEX_REQUEST_INVALID": BRIDGE_EXECUTION_FAILED,
    "CODEX_CANCELLED": BRIDGE_EXECUTION_FAILED,
    "CODEX_STOPPED": BRIDGE_EXECUTION_FAILED,
    "BRIDGE_WORKER_ERROR": BRIDGE_EXECUTION_FAILED,
    "BRIDGE_RESULT_MISSING": BRIDGE_EXECUTION_FAILED,
}


def category_for_structured_code(code: object) -> str:
    """Return a category only for error codes observed in the supported bridge API."""
    if not isinstance(code, str):
        return UNKNOWN
    return STRUCTURED_ERROR_CATEGORIES.get(code, UNKNOWN)
